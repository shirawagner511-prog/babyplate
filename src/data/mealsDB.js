// ─── Helper functions ────────────────────────────────────────────────────────

export const getMealsByAge = (ageMonths) =>
  mealsDB.filter(m => ageMonths >= m.ageMin && ageMonths <= m.ageMax)

export const getMealsByType = (mealType) =>
  mealsDB.filter(m => m.mealType === mealType)

export const getMealsByAgeAndType = (ageMonths, mealType) =>
  mealsDB.filter(m =>
    ageMonths >= m.ageMin &&
    ageMonths <= m.ageMax &&
    (mealType === 'all' || m.mealType === mealType)
  )

export const searchMeals = (query, ageMonths = null) => {
  const q = query.toLowerCase()
  return mealsDB.filter(m => {
    const matchesQuery =
      m.name.toLowerCase().includes(q) ||
      m.ingredients.some(i => i.toLowerCase().includes(q)) ||
      m.nutritionNote.toLowerCase().includes(q)
    const matchesAge = ageMonths
      ? ageMonths >= m.ageMin && ageMonths <= m.ageMax
      : true
    return matchesQuery && matchesAge
  })
}

